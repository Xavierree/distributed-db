CREATE POLICY "Public Manage Products" ON products FOR ALL USING (true);
CREATE POLICY "Public Write Transactions" ON transactions FOR ALL USING (true);
CREATE POLICY "Public Write Items" ON transaction_items FOR ALL USING (true);
